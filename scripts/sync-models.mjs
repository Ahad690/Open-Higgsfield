// Scans generation/catalog/models/*.ts and writes generation/catalog/models.generated.ts
// (the MODELS barrel). Runs from next.config.ts on every dev/build and via `pnpm models`,
// so adding a model is one file. Adapted from higgsfield-ai/app-templates.
import { existsSync, mkdirSync, readdirSync, readFileSync, watch, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const MODELS_DIR = join(ROOT, "generation/catalog/models")
const BARREL = join(ROOT, "generation/catalog/models.generated.ts")

export function syncModels() {
  mkdirSync(MODELS_DIR, { recursive: true })
  const names = readdirSync(MODELS_DIR)
    .filter((file) => file.endsWith(".ts") && !file.endsWith(".d.ts"))
    .map((file) => file.slice(0, -3))
    .sort()
  const changed = writeIfChanged(BARREL, renderBarrel(names))
  return { names, changed }
}

/** Dev only: re-sync when a model file is added or removed. */
export function watchModels() {
  mkdirSync(MODELS_DIR, { recursive: true })
  let timer
  watch(MODELS_DIR, (_event, file) => {
    if (!file || !file.endsWith(".ts")) return
    clearTimeout(timer)
    timer = setTimeout(() => {
      const { names, changed } = syncModels()
      if (changed) console.log(`[models] ${names.length} model files, barrel updated`)
    }, 150)
  }).unref()
}

function renderBarrel(names) {
  const imports = names.map((name, i) => `import m${i} from "./models/${name}"`).join("\n")
  const list = names.map((_, i) => `m${i}`).join(", ")
  return `// Generated by scripts/sync-models.mjs from generation/catalog/models/*. Do not edit.
import type { ModelEntry } from "./types"

${imports}

const LAST = Number.MAX_SAFE_INTEGER

const installed: (ModelEntry | ModelEntry[])[] = [${list}]

export const MODELS: readonly ModelEntry[] = installed
  .flat()
  .sort((a, b) => (a.order ?? LAST) - (b.order ?? LAST))
`
}

function writeIfChanged(path, content) {
  if (existsSync(path) && readFileSync(path, "utf8") === content) return false
  writeFileSync(path, content)
  return true
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const { names, changed } = syncModels()
  console.log(`[models] ${names.length} model files${changed ? ", barrel updated" : ", up to date"}`)
}
